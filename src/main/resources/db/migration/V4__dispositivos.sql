-- ============================================================
-- M13: dispositivos para push nativo (Expo Push Service).
--
-- Un usuario puede tener varios dispositivos (celular, tablet).
-- El token es único: si el mismo dispositivo cambia de cuenta,
-- la fila se reasigna al usuario que inicia sesión.
-- ============================================================

CREATE TABLE public.dispositivos (
    id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    usuario_id bigint NOT NULL,
    token character varying(255) NOT NULL,
    plataforma character varying(20) NOT NULL,
    CONSTRAINT dispositivos_plataforma_check CHECK (((plataforma)::text = ANY ((ARRAY['ANDROID'::character varying, 'IOS'::character varying, 'WEB'::character varying])::text[])))
);

ALTER TABLE public.dispositivos ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.dispositivos_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.dispositivos
    ADD CONSTRAINT dispositivos_pkey PRIMARY KEY (id);

-- Un token identifica un dispositivo físico, no una cuenta.
ALTER TABLE ONLY public.dispositivos
    ADD CONSTRAINT dispositivos_token_key UNIQUE (token);

-- Al borrar una cuenta se limpian sus dispositivos. En producción
-- las cuentas no se borran (baja lógica), pero en tests sí.
ALTER TABLE ONLY public.dispositivos
    ADD CONSTRAINT dispositivos_usuario_id_fkey
    FOREIGN KEY (usuario_id) REFERENCES public.users(id) ON DELETE CASCADE;

CREATE INDEX idx_dispositivos_usuario
    ON public.dispositivos USING btree (usuario_id);
