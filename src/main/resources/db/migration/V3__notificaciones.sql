-- ============================================================
-- M12: notificaciones persistentes y push por WebSocket.
--
-- Una fila por destinatario y evento. La tabla es la fuente de
-- verdad: el WebSocket solo acelera la entrega.
-- ============================================================

CREATE TABLE public.notificaciones (
    id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    usuario_id bigint NOT NULL,
    tipo character varying(30) NOT NULL,
    titulo character varying(120) NOT NULL,
    mensaje character varying(500) NOT NULL,
    referencia_id bigint,
    leida boolean NOT NULL,
    leida_at timestamp(6) without time zone,
    CONSTRAINT notificaciones_tipo_check CHECK (((tipo)::text = ANY ((ARRAY['COMUNICADO'::character varying, 'TICKET_RESUELTO'::character varying, 'CALIFICACION'::character varying, 'ASISTENCIA'::character varying, 'MATERIAL'::character varying, 'CIERRE'::character varying])::text[])))
);

ALTER TABLE public.notificaciones ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.notificaciones_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.notificaciones
    ADD CONSTRAINT notificaciones_pkey PRIMARY KEY (id);

-- Al borrar una cuenta se limpian sus notificaciones. En producción
-- las cuentas no se borran (baja lógica), pero en tests sí.
ALTER TABLE ONLY public.notificaciones
    ADD CONSTRAINT notificaciones_usuario_id_fkey
    FOREIGN KEY (usuario_id) REFERENCES public.users(id) ON DELETE CASCADE;

CREATE INDEX idx_notificaciones_usuario_leida
    ON public.notificaciones USING btree (usuario_id, leida);
